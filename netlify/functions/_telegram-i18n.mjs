export function tg(language, key, values = {}) {
  const selected = messages[telegramLanguage(language)] || messages.en;
  let value = selected[key] || messages.en[key] || key;

  for (const [name, replacement] of Object.entries(values)) {
    value = value.replaceAll(
      `{{${name}}}`,
      String(replacement ?? "")
    );
  }

  return value;
}
